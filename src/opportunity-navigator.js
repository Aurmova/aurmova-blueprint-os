function decisionStage(q=""){
  const s=String(q||"");
  if(/已经开始|已经做|已经卖|有顾客|正在做|开了|经营中/.test(s))return "已经行动，正在优化";
  if(/准备|打算|考虑|想试|想开始|计划/.test(s))return "正在考虑，准备试水";
  if(/不知道|迷茫|没方向|不懂|不确定/.test(s))return "还在探索，先缩小选择";
  return "先确认目标，再决定行动";
}
