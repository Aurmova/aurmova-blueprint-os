function motiveOptions(role,intent){
  if(["career","income","entrepreneurship","jobchange","expansion","direction"].includes(intent.id))return CAREER_MOTIVES;
  if(intent.id==="relationship")return["想减少争吵","想被理解","想知道要不要继续","想学会表达边界","想修复信任"];
  if(intent.id==="parenting")return["想让孩子更愿意沟通","想改善学习／规则冲突","想知道该怎么教","想理解孩子真正需要什么","想减少家庭压力"];
  if(intent.id==="money")return["想增加收入","想存得下钱","想减少财务压力","想评估创业风险","想建立更稳定的现金流"];
  return["想弄清真正的问题","想知道有哪些选择","想找一个可执行的下一步"];
}
function firstQuestion(role,intent){
  if(["career","income","entrepreneurship","jobchange","expansion","direction"].includes(intent.id)){
    return "你说想要事业／收入／改变，我先不直接把它等同于创业。你现在最想得到的到底是哪一个：自己的收入、成就感、时间自主、离开现在的环境，还是建立一份真正属于自己的事业？";
  }
  if(intent.id==="relationship")return "你最想改变的是对方、你们的互动方式，还是你自己在这段关系里的感受和选择？";
  if(intent.id==="parenting")return "最近最让你困扰的一次亲子场景是什么？当时你说了什么、孩子怎么反应、最后怎么收尾？";
  if(intent.id==="money")return "你说的钱的问题，现在更像是收入不够、留不住、支出压力大，还是正在考虑一个有风险的决定？";
  return "如果这次咨询只能解决一个问题，你最希望30天后哪一件事真的不一样？";
}
function branchPrompts(intent){
  if(["career","income","entrepreneurship","jobchange","expansion","direction"].includes(intent.id))return[
    {when:"如果她说「我只是想有自己的收入」",reply:"那我们先不急着谈开公司。先找一条成本低、时间可控、能验证付费需求的收入路径。"},
    {when:"如果她说「我想找回价值感」",reply:"那目标不只是赚钱。我们要找一件能累积作品、能力和被看见感的事，收入可以作为第二层验证。"},
    {when:"如果她说「我真的想创业」",reply:"可以，但我们先验证客户和需求，再谈投入。第一目标不是租店或辞职，而是拿到第一个真实付费。"},
    {when:"如果她说「我还不知道」",reply:"没关系，那就不逼自己选。我们保留2–3条路，用7天小实验帮你排除，而不是靠想象做决定。"}
  ];
  return[
    {when:"如果顾客说「对」",reply:"继续追问最近一次具体例子，确认这是偶发还是重复模式。"},
    {when:"如果顾客说「不像」",reply:"不硬套数字，换另一个生活场景；如果还是不匹配，就先放下这条假设。"}
  ];
}
function numericHints(blueprint,highPeak){
  if(!blueprint)return[];
  const picks=[
    {label:"主性格",n:Number(blueprint.mainPersonality)},
    {label:"内心数字",n:Number(blueprint.innerCode)},
    {label:"潜意识",n:Number(blueprint.subconsciousCode)}
  ];
  if(highPeak?.current?.number)picks.push({label:"当前高峰",n:Number(highPeak.current.number)});
  return picks.filter(x=>DIGIT_ACTION[x.n]).map(x=>({label:x.label,number:x.n,...DIGIT_ACTION[x.n]}));
}
export function buildOpportunityNavigator(input={}){
  const occupation=String(input.occupation||"");
  const question=String(input.question||"");
  const role=detectRole(occupation);
  const intent=detectIntent(question,input.theme);
  const isCareer=["career","income","entrepreneurship","jobchange","expansion","direction"].includes(intent.id);
  let paths=isCareer?careerPaths(role,intent):nonCareerPaths(intent);
  if(!paths.length)paths=careerPaths(role,{id:"direction"});
  return{
    role,intent,stage:decisionStage(question),
    keywords:keywordsFor(role,intent),
    motives:motiveOptions(role,intent),
    firstQuestion:firstQuestion(role,intent),
    branches:branchPrompts(intent),
    paths:paths.slice(0,5),
    numericHints:numericHints(input.blueprint,input.highPeak),
    summary:isCareer
      ?"这里不是替顾客选职业，而是把“想改变”拆成几条现实可验证的路，再让顾客自己选择。"
      :"这个主题先以真实经历与顾客回答为主，行业只是背景，不强行套事业路线。",
    boundary:"AURMOVA数字层只用来补充行动偏好、沟通方式、风险点与节奏，不用来替顾客决定辞职、创业、投资、离婚或其他重大选择。现实条件与顾客本人意愿优先。"
  };
}
