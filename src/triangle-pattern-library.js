export function getInnerOuterAlignment(number,innerCount,outerCount){
  const data=INNER_OUTER_ALIGNMENT_LIBRARY[number];
  if(!data) return null;
  const innerHigh=Number(innerCount)>=2;
  const outerHigh=Number(outerCount)>=2;
  if(innerHigh&&outerHigh) return {mode:"consistent",modeName:"内外一致型",tagline:"里里外外都是同一个人",...data.consistent};
  if(innerHigh&&!outerHigh) return {mode:"suppressed",modeName:"内在压抑型",tagline:"真实的你被藏起来了",...data.suppressed};
  if(!innerHigh&&outerHigh) return {mode:"compensating",modeName:"外在补偿型",tagline:"现实让你活出了另一套表现",...data.compensating};
  return {mode:"low",modeName:"低密度型",tagline:"这个数字目前不是内外结构里的主要角色",label:"内外都偏少",hook:"这个数字存在感较低。",body:"内外两边都没有形成高密度，因此先不把它当作主要人格冲突或一致主题。",focus:"咨询时优先看其他高密度数字、缺失数与所在位置。"};
}
