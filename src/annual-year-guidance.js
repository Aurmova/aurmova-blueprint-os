export function prepareAnnualYearGuidance(snapshot,childMode=false){
 const n=Number(snapshot?.personal?.number);
 const data=ANNUAL_YEAR_GUIDANCE[n];
 if(!data||!Number.isInteger(Number(snapshot?.year)))return null;
 const groups=snapshot?.personalAxis?.groups||{};
 const codes=groups.MNO&&groups.MOQ&&groups.NOP&&groups.PQR?
   {MNO:groups.MNO.join(""),MOQ:groups.MOQ.join(""),NOP:groups.NOP.join(""),PQR:groups.PQR.join("")}:null;
 const year=Number(snapshot.year);
 const talk=childMode?data.child.talk:data.talk;
 return {number:n,year,data,childMode,codes,talk};
}

